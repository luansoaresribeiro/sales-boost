create or replace function pg_temp.sb_add_en(j jsonb, m jsonb) returns jsonb language plpgsql as $fn$
declare k text; v jsonb; o jsonb; i int;
begin
  if jsonb_typeof(j) = 'object' then
    o := '{}'::jsonb;
    for k, v in select * from jsonb_each(j) loop
      o := o || jsonb_build_object(k, pg_temp.sb_add_en(v, m));
    end loop;
    if jsonb_typeof(o->'pt') = 'string' and (o->>'en') is null and m ? (o->>'pt') then o := o || jsonb_build_object('en', m->>(o->>'pt')); end if; -- [ADD]
    -- if jsonb_typeof(o->'pt') = 'string' and m ? (o->>'pt') and o->>'en' = m->>(o->>'pt') then o := o - 'en'; end if; -- [UNDO]
    return o;
  elsif jsonb_typeof(j) = 'array' then
    o := '[]'::jsonb;
    for i in 0 .. jsonb_array_length(j) - 1 loop
      o := o || jsonb_build_array(pg_temp.sb_add_en(j->i, m));
    end loop;
    return o;
  end if;
  return j;
end $fn$;

