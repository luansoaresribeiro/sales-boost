import { useEffect, useRef, useState } from 'react'
import tourMp4 from '../../assets/loader/tour.mp4'
import tourWebm from '../../assets/loader/tour.webm'
import tourPoster from '../../assets/loader/tour-poster.webp'

// Fundo animado da tela de espera do diagnóstico (roteiro do dono, 2026-10-17):
//  1) fotos do imóvel flutuam soltas na frente — são quadros do próprio tour,
//     pra ficar claro que o tour nasceu delas;
//  2) elas se juntam no centro e viram o TOUR VIRTUAL (gerado pela IA do Sales Boost);
//  3) o tour acaba e os criativos aparecem um por vez no mesmo lugar;
//  4) o tempo todo, criativos do Sales Boost passam ao fundo, desfocados.
// Repete enquanto o diagnóstico roda; não segura nem atrasa nada (quem decide
// quando sai é o DiagnosisLoader, pelo andamento real). Com "reduzir movimento",
// fica uma composição parada (tour + criativos, sem vídeo rodando).
// Imagens/vídeo: conta de teste (tour de um apartamento + criativos gerados
// com fotos de teste). Nada de arte de outras empresas.

const photos = Object.values(import.meta.glob('../../assets/loader/photo-*.webp', { eager: true, import: 'default' })) as string[]
const designMap = import.meta.glob('../../assets/loader/design-*.webp', { eager: true, import: 'default' }) as Record<string, string>
const designs = Object.values(designMap)
// Os de destaque (um por vez depois do tour): os modelos 5 a 10, nessa ordem.
const spotlight = [5, 6, 7, 8, 9, 10].map(n => designMap[`../../assets/loader/design-${n}.webp`]).filter(Boolean)

type Pose = { x: number; y: number; r: number; s: number; o: number }

// Ciclo (s): fotos entram → flutuam → se juntam → tour → tour sai →
// criativos um por vez → recomeça.
const SPOT = 2.8
const SPOT_START = 26.4
const K = { inEnd: 1.8, gather: 6.5, gathered: 8.6, tourIn: 7.8, tourOn: 9.4, tourOut: 25.5, tourEnd: 27, cycle: SPOT_START + spotlight.length * SPOT + 0.4 }
const ease = (u: number) => (u <= 0 ? 0 : u >= 1 ? 1 : u < 0.5 ? 4 * u * u * u : 1 - Math.pow(-2 * u + 2, 3) / 2)
const mix = (a: Pose, b: Pose, u: number): Pose => {
  const e = ease(u)
  return { x: a.x + (b.x - a.x) * e, y: a.y + (b.y - a.y) * e, r: a.r + (b.r - a.r) * e, s: a.s + (b.s - a.s) * e, o: a.o + (b.o - a.o) * e }
}
const seg = (t: number, a: number, b: number) => (t - a) / (b - a)

// Posições normalizadas (−0.5…0.5 da largura/altura). O painel do carregamento
// fica embaixo: as fotos ocupam o alto e as laterais.
const SCATTER: Pose[] = [
  { x: -0.33, y: -0.3, r: -9, s: 1, o: 1 }, { x: 0.3, y: -0.34, r: 7, s: 0.9, o: 1 },
  { x: -0.05, y: -0.2, r: 3, s: 1.12, o: 1 }, { x: 0.36, y: -0.02, r: -5, s: 0.85, o: 1 },
  { x: -0.38, y: 0.05, r: 6, s: 0.8, o: 1 }, { x: 0.14, y: -0.4, r: -4, s: 0.75, o: 1 },
  { x: -0.2, y: -0.42, r: 8, s: 0.7, o: 1 }, { x: 0.4, y: 0.28, r: 4, s: 0.7, o: 1 },
]
const OFF = (i: number): Pose => {
  const d = [[-1, -0.6], [1, -0.7], [0, -1], [1, 0.1], [-1, 0.2], [0.5, -1], [-0.6, -1], [1, 0.8]][i % 8]
  return { x: d[0] * 0.9, y: d[1] * 0.9, r: d[0] * 20, s: 0.8, o: 0 }
}

function photoPose(i: number, t: number, center: { x: number; y: number }): Pose {
  const sc = SCATTER[i % SCATTER.length]
  const scatter = { ...sc, x: sc.x + Math.sin(t * 0.6 + i * 1.7) * 0.012, y: sc.y + Math.cos(t * 0.5 + i) * 0.012, r: sc.r + Math.sin(t * 0.4 + i) * 1.2 }
  // Juntam no centro do tour, encolhendo e sumindo dentro dele (um pouco escalonadas).
  const into: Pose = { x: center.x, y: center.y, r: 0, s: 0.55, o: 0 }
  const lag = i * 0.12
  if (t < K.inEnd) return mix(OFF(i), scatter, seg(t, 0, K.inEnd))
  if (t < K.gather + lag) return scatter
  if (t < K.gathered + lag) return mix(scatter, into, seg(t, K.gather + lag, K.gathered + lag))
  return into
}

const prefersReduced = () => typeof window !== 'undefined' && !!window.matchMedia?.('(prefers-reduced-motion: reduce)').matches

const BADGE = { pt: 'Tour virtual gerado pela IA do Sales Boost', en: 'Virtual tour generated by Sales Boost AI' }

export default function LoaderShowcase({ lang = 'pt' }: { lang?: 'pt' | 'en' }) {
  const box = useRef<HTMLDivElement>(null)
  const photoEls = useRef<(HTMLDivElement | null)[]>([])
  const laneEls = useRef<(HTMLDivElement | null)[]>([])
  const tourEl = useRef<HTMLDivElement>(null)
  const spotEls = useRef<(HTMLDivElement | null)[]>([])
  const video = useRef<HTMLVideoElement>(null)
  const [reduced] = useState(prefersReduced)

  useEffect(() => {
    const el = box.current
    if (!el) return
    let playing = false
    const vid = video.current
    const paint = (t: number, clock: number) => {
      const w = el.clientWidth, h = el.clientHeight
      // Tour: o maior que couber acima do painel do carregamento (4:3).
      const tourH = Math.max(150, Math.min(w * 0.84 * 0.75, h - 440, 420))
      const tourW = tourH / 0.75
      const center = { x: 0, y: (16 + tourH / 2) / h - 0.5 }
      const cardW = Math.min(200, Math.max(100, w * 0.16))

      photoEls.current.forEach((c, i) => {
        if (!c) return
        const p = photoPose(i, t, center)
        c.style.width = `${cardW}px`
        c.style.opacity = String(p.o)
        c.style.transform = `translate(-50%,-50%) translate(${p.x * w}px,${p.y * h}px) rotate(${p.r}deg) scale(${p.s})`
      })

      // Tour entra crescendo de dentro das fotos, flutua de leve e sai.
      const tc = tourEl.current
      if (tc) {
        let s = 0.5, o = 0
        if (t >= K.tourIn && t < K.tourOn) { const u = ease(seg(t, K.tourIn, K.tourOn)); s = 0.5 + 0.5 * u; o = u }
        else if (t >= K.tourOn && t < K.tourOut) { s = 1; o = 1 }
        else if (t >= K.tourOut && t < K.tourEnd) { const u = ease(seg(t, K.tourOut, K.tourEnd)); s = 1 - 0.15 * u; o = 1 - u }
        const fy = Math.sin(clock * 0.7) * 4, fr = Math.sin(clock * 0.45) * 0.6
        tc.style.width = `${tourW}px`
        tc.style.opacity = String(o)
        tc.style.transform = `translate(-50%,-50%) translate(0px,${center.y * h + fy}px) rotate(${fr}deg) scale(${s})`
        const v = vid
        if (v && !reduced) {
          if (o > 0 && !playing) { playing = true; try { v.currentTime = 0 } catch { /* ainda carregando */ } void v.play().catch(() => {}) }
          if (o === 0 && playing) { playing = false; v.pause() }
        }
      }

      // Depois do tour: um criativo por vez, no mesmo lugar (entra, fica, sai).
      spotEls.current.forEach((c, k) => {
        if (!c) return
        const u = (t - SPOT_START - k * SPOT) / SPOT
        let o = 0, s = 0.92
        if (u >= 0 && u < 1) {
          o = u < 0.15 ? ease(u / 0.15) : u > 0.85 ? 1 - ease((u - 0.85) / 0.15) : 1
          s = 0.92 + 0.1 * u
        }
        c.style.height = `${tourH}px`
        c.style.opacity = String(o)
        c.style.transform = `translate(-50%,-50%) translate(0px,${center.y * h}px) scale(${s})`
      })

      // Criativos ao fundo: duas faixas deslizando em sentidos opostos, sem parar.
      const lw = Math.min(190, Math.max(110, w * 0.3)), gap = lw * 1.12
      const half = Math.ceil(designs.length / 2)
      laneEls.current.forEach((c, i) => {
        if (!c) return
        const row = i < half ? 0 : 1, k = row ? i - half : i
        const n = row ? designs.length - half : half
        const span = Math.max(n * gap, w + gap * 2)
        const speed = row ? -16 : 20
        let x = k * gap + clock * speed
        x = ((x % span) + span) % span - gap
        // Computador: faixas nas laterais do tour. Celular (tour ocupa a largura):
        // uma faixa aparece no vão entre o tour e o painel, a outra espia atrás do tour.
        const narrow = w < 700
        const y = narrow ? (row ? 16 - lw * 0.45 : 16 + tourH - 22) : (row ? h * 0.56 : h * 0.12)
        c.style.width = `${lw}px`
        c.style.transform = `translate(${x}px,${y}px) rotate(${row ? 3 : -3}deg)`
      })
    }
    if (reduced) { paint(K.tourOn + 1, 0); return }
    let raf = 0
    const t0 = performance.now()
    const tick = (now: number) => {
      const clock = Math.max(0, now - t0) / 1000
      paint(clock % K.cycle, clock)
      raf = requestAnimationFrame(tick)
    }
    raf = requestAnimationFrame(tick)
    return () => { cancelAnimationFrame(raf); vid?.pause() }
  }, [reduced])

  const card: React.CSSProperties = { position: 'absolute', left: '50%', top: '50%', aspectRatio: '4 / 5', borderRadius: 14, overflow: 'hidden', willChange: 'transform, opacity', opacity: 0, boxShadow: '0 18px 50px rgba(0,0,0,0.55)', border: '1px solid rgba(255,255,255,0.12)' }
  const img: React.CSSProperties = { width: '100%', height: '100%', objectFit: 'cover', display: 'block' }

  return (
    <div ref={box} aria-hidden style={{ position: 'absolute', inset: 0, overflow: 'hidden', pointerEvents: 'none' }}>
      {/* fundo: criativos desfocados passando */}
      {designs.map((src, i) => (
        <div key={src} ref={el => { laneEls.current[i] = el }}
          style={{ position: 'absolute', left: 0, top: 0, aspectRatio: '4 / 5', borderRadius: 14, overflow: 'hidden', willChange: 'transform', opacity: 0.55, zIndex: 0, boxShadow: '0 16px 40px rgba(0,0,0,0.5)' }}>
          <img src={src} alt="" style={{ ...img, filter: 'blur(2.6px)', transform: 'scale(1.06)' }} decoding="async" />
        </div>
      ))}
      {/* frente: fotos soltas */}
      {photos.map((src, i) => (
        <div key={src} ref={el => { photoEls.current[i] = el }} style={{ ...card, zIndex: 3 + (i % 3) }}>
          <img src={src} alt="" style={img} decoding="async" />
        </div>
      ))}
      {/* tour virtual: nasce das fotos */}
      <div ref={tourEl} style={{ position: 'absolute', left: '50%', top: '50%', aspectRatio: '4 / 3', borderRadius: 18, overflow: 'hidden', willChange: 'transform, opacity', opacity: 0, zIndex: 8, boxShadow: '0 30px 90px rgba(0,0,0,0.7), 0 0 0 1px rgba(255,255,255,0.14)', background: '#000' }}>
        {reduced
          ? <img src={tourPoster} alt="" style={img} />
          : (
            // WebM (Chrome/Android/Firefox) e MP4 (Safari/iPhone): cada navegador baixa só o que toca
            <video ref={video} poster={tourPoster} muted playsInline loop preload="auto" style={img}>
              <source src={tourWebm} type="video/webm" />
              <source src={tourMp4} type="video/mp4" />
            </video>
          )}
        <div style={{ position: 'absolute', left: 12, top: 12, display: 'flex', alignItems: 'center', gap: 6, background: 'rgba(0,0,0,0.5)', color: 'white', fontSize: 11, fontWeight: 700, letterSpacing: '0.02em', padding: '5px 10px', maxWidth: 'calc(100% - 24px)', borderRadius: 99, fontFamily: "'Bricolage Grotesque', system-ui, sans-serif" }}>
          <span style={{ width: 7, height: 7, borderRadius: 99, background: '#FF6D29', flexShrink: 0 }} /> {BADGE[lang]}
        </div>
      </div>
      {/* depois do tour: criativos em destaque, um por vez */}
      {spotlight.map((src, k) => (
        <div key={src} ref={el => { spotEls.current[k] = el }}
          style={{ position: 'absolute', left: '50%', top: '50%', aspectRatio: '4 / 5', borderRadius: 16, overflow: 'hidden', willChange: 'transform, opacity', opacity: 0, zIndex: 9, boxShadow: '0 30px 90px rgba(0,0,0,0.7), 0 0 0 1px rgba(255,255,255,0.14)' }}>
          <img src={src} alt="" style={img} decoding="async" />
        </div>
      ))}
    </div>
  )
}
